"""
Hybrid Triage Engine: AI Decision-Support Heuristics + Deterministic Rule Engine.

IMPORTANT DISCLAIMER:
This module implements a RESEARCH PROTOTYPE decision-support heuristic for emergency
ambulance dispatch. It is NOT clinically validated triage and is NOT intended for
unsupervised diagnostic or therapeutic deployment. All outputs require human dispatcher
verification and confirmation.

Architecture:
- LLM Layer: understands unstructured free-text, extracts clinical symptoms, identifies
  mentions of location/patients, and suggests initial triage classification.
- Deterministic Rule Layer: strictly validates clinical severity, applies authoritative
  prototype BLS/ALS category mapping, enforces Multi-Casualty Incident (MCI) rules,
  detects contradictions, and overrides unsafe/conflicting AI suggestions.
- Auditing: Stores both AI suggestions and deterministic rule outputs side-by-side.
"""
import re
import logging
from typing import List, Optional
from pydantic import BaseModel, Field

from app.models.case import SeverityLevel, AmbulanceType
from app.ai.schemas import EmergencyExtractionResult

logger = logging.getLogger(__name__)

PROTOTYPE_DISCLAIMER = (
    "PROTOTYPE DECISION-SUPPORT HEURISTIC: NOT clinically validated triage. "
    "Requires mandatory human dispatcher review and confirmation."
)

DECISION_TYPE_HEURISTIC = "PROTOTYPE_DECISION_SUPPORT_HEURISTIC"

# Authoritative prototype severity to ambulance mapping
PROTOTYPE_AMBULANCE_MAP = {
    SeverityLevel.CRITICAL: AmbulanceType.ALS,
    SeverityLevel.HIGH: AmbulanceType.ALS,
    SeverityLevel.MODERATE: AmbulanceType.BLS,
    SeverityLevel.LOW: AmbulanceType.BLS,
    SeverityLevel.UNKNOWN: AmbulanceType.UNKNOWN,  # UNKNOWN must NOT become ALS
}

# Critical red flag markers that mandate ALS regardless of LLM suggestion
CRITICAL_SYMPTOM_MARKERS = [
    "cardiac arrest", "cardiac collapse", "cardiac", "chest pain", "heart attack",
    "unconscious", "collapsed", "collapse", "in shock",
    "not breathing", "stopped breathing", "gasping", "arterial bleeding",
    "severe hemorrhage", "head trauma", "crushed", "choking", "seizure",
    "stroke", "paralysis", "anaphylaxis", "severe burns",
    "हृदयविकाराचा झटका", "हार्ट अटॅक", "दिल का दौरा", "बेहोश", "बेशुद्ध",
    "श्वास बंद", "सांस बंद", "रक्तस्राव", "पक्षाघात", "लकवा"
]


class DeterministicTriageResult(BaseModel):
    """
    Consolidated decision result generated by the hybrid AI + rule engine.
    Audits both AI suggestion and deterministic rule outputs.
    """
    final_severity: SeverityLevel
    final_ambulance: AmbulanceType
    ai_suggested_severity: SeverityLevel
    ai_suggested_ambulance: AmbulanceType
    deterministic_severity: SeverityLevel
    deterministic_ambulance: AmbulanceType
    has_conflict: bool = False
    conflict_reason: Optional[str] = None
    mandatory_human_review: bool = False
    review_triggers: List[str] = Field(default_factory=list)
    clinical_rationale: str
    decision_type: str = DECISION_TYPE_HEURISTIC
    disclaimer: str = PROTOTYPE_DISCLAIMER
    is_multi_patient: bool = False
    patient_count: int = 1


def evaluate_hybrid_triage(
    extraction: EmergencyExtractionResult,
    raw_text: str,
) -> DeterministicTriageResult:
    """
    Execute hybrid triage evaluation:
    1. Parse LLM suggestions (severity, symptoms, patient count, ambulance).
    2. Run deterministic validation rules (red flags, multi-patient, missing/vague symptoms).
    3. Detect conflicts between LLM and deterministic rules, overriding toward patient safety.
    4. Apply prototype BLS/ALS mapping:
       Critical → ALS
       High → ALS
       Moderate → BLS
       Low → BLS
       Unknown → ALS + mandatory human review
    5. Return consolidated result with side-by-side audit and prototype disclaimer.
    """
    raw_lower = raw_text.lower()
    symptoms_joined = " ".join(s.lower() for s in extraction.symptoms)
    combined_clinical = f"{raw_lower} {symptoms_joined}"

    ai_sev = extraction.severity
    ai_amb = extraction.ambulance_requirement
    patient_count = max(1, extraction.patient_count)
    is_multi_patient = patient_count > 1

    review_triggers: List[str] = []
    overrides: List[str] = []
    conflict_reasons: List[str] = []

    # -------------------------------------------------------------------------
    # Rule 1: Multi-Patient Scenario (Mass Casualty / Overwhelm Prevention)
    # -------------------------------------------------------------------------
    rule_severity = ai_sev
    if is_multi_patient:
        if patient_count >= 4 or any(w in raw_lower for w in ["bus", "train", "mass", "pileup", "many people"]):
            rule_severity = SeverityLevel.CRITICAL
            overrides.append(f"Multiple casualties ({patient_count} patients) escalated severity to CRITICAL (MCI Level 2).")
        elif rule_severity in (SeverityLevel.MODERATE, SeverityLevel.LOW, SeverityLevel.UNKNOWN):
            rule_severity = SeverityLevel.HIGH
            overrides.append(f"Multiple casualties ({patient_count} patients) escalated severity to HIGH (MCI Level 1).")

    # -------------------------------------------------------------------------
    # Rule 2: Critical Clinical Red Flags
    # -------------------------------------------------------------------------
    has_critical_flag = any(flag in combined_clinical for flag in CRITICAL_SYMPTOM_MARKERS)
    if extraction.conscious_status in ("unconscious", "semi-conscious") or extraction.breathing_status in ("stopped", "gasping"):
        has_critical_flag = True

    if has_critical_flag:
        if rule_severity in (SeverityLevel.MODERATE, SeverityLevel.LOW, SeverityLevel.UNKNOWN):
            rule_severity = SeverityLevel.CRITICAL
            overrides.append("Presence of life-threat clinical signs enforced CRITICAL priority.")

    # -------------------------------------------------------------------------
    # Rule 3: Missing Symptoms Handling
    # -------------------------------------------------------------------------
    is_missing_symptoms = (
        not extraction.symptoms
        or extraction.symptoms == ["reported distress"]
        or all(len(s.strip()) < 3 for s in extraction.symptoms)
    ) and not has_critical_flag

    if is_missing_symptoms:
        rule_severity = SeverityLevel.UNKNOWN
        review_triggers.append("No clinical symptoms identified in emergency report; requires caller callback.")

    # -------------------------------------------------------------------------
    # Rule 4: Unknown or Vague Emergency Handling
    # -------------------------------------------------------------------------
    is_unknown_or_vague = (
        extraction.emergency_type.lower() in ("unknown", "unclear", "unclear/pending", "pending")
        or (is_missing_symptoms and len(raw_text.split()) < 6)
    ) and not has_critical_flag

    if is_unknown_or_vague:
        rule_severity = SeverityLevel.UNKNOWN
        review_triggers.append("Emergency nature is vague or unknown; requires human dispatcher assessment.")

    # -------------------------------------------------------------------------
    # Rule 5: Contradictory Symptoms Handling
    # -------------------------------------------------------------------------
    if extraction.is_contradictory:
        # In presence of contradictions, err on side of safety
        if rule_severity in (SeverityLevel.MODERATE, SeverityLevel.LOW):
            rule_severity = SeverityLevel.HIGH
            overrides.append("Contradictory caller claims escalated acuity to HIGH for precautionary ALS dispatch.")
        review_triggers.append(f"Contradictory symptoms reported: {extraction.contradiction_notes or 'incompatible states'}.")

    # -------------------------------------------------------------------------
    # Rule 6: Authoritative Prototype Ambulance Mapping
    # Critical → ALS, High → ALS, Moderate → BLS, Low → BLS, Unknown → UNKNOWN + review
    # -------------------------------------------------------------------------
    rule_ambulance = PROTOTYPE_AMBULANCE_MAP.get(rule_severity, AmbulanceType.UNKNOWN)

    if rule_severity == SeverityLevel.UNKNOWN:
        rule_ambulance = AmbulanceType.UNKNOWN
        review_triggers.append("Clinical assessment is UNKNOWN due to insufficient information. Mandatory human dispatcher review is required.")

    # -------------------------------------------------------------------------
    # Rule 7: Conflict Detection & Reconciliation (LLM vs Deterministic Engine)
    # -------------------------------------------------------------------------
    has_conflict = False

    # Severity mismatch
    if ai_sev != rule_severity:
        has_conflict = True
        conflict_reasons.append(
            f"Severity Discrepancy: LLM suggested '{ai_sev.value}', deterministic rules validated '{rule_severity.value}'."
        )

    # Ambulance mismatch
    if ai_amb != rule_ambulance:
        has_conflict = True
        conflict_reasons.append(
            f"Ambulance Discrepancy: LLM suggested '{ai_amb.value}', deterministic mapping assigned '{rule_ambulance.value}'."
        )

    # If LLM proposed BLS but deterministic rule requires ALS (safety override)
    if ai_amb == AmbulanceType.BLS and rule_ambulance == AmbulanceType.ALS:
        overrides.append("Deterministic safety override: Upgraded ambulance from BLS to ALS.")
    elif rule_severity == SeverityLevel.UNKNOWN or rule_ambulance == AmbulanceType.UNKNOWN:
        overrides.append("AI recommendation differs from deterministic assessment. Available clinical information is insufficient for automatic dispatch. Human dispatcher review is required.")

    if has_conflict:
        review_triggers.append("Discrepancy detected between LLM recommendation and deterministic rule engine.")

    # Final consolidated decisions:
    # UNKNOWN MUST NOT become ALS or BLS. It remains UNKNOWN with mandatory review.
    if rule_severity == SeverityLevel.UNKNOWN or rule_ambulance == AmbulanceType.UNKNOWN:
        final_severity = SeverityLevel.UNKNOWN
        final_ambulance = AmbulanceType.UNKNOWN
    else:
        final_severity = rule_severity
        final_ambulance = rule_ambulance

    # Mandatory review if severity or ambulance is UNKNOWN or conflicts exist or confidence is low
    mandatory_review = (
        final_severity == SeverityLevel.UNKNOWN
        or final_ambulance == AmbulanceType.UNKNOWN
        or has_conflict
        or bool(review_triggers)
        or extraction.confidence_score < 0.75
    )

    # Assemble comprehensive rationale clearly labeled as prototype heuristic
    rationale_parts = [
        f"[{PROTOTYPE_DISCLAIMER}]",
        f"Recommendation: {final_severity.value} severity with {final_ambulance.value} ambulance.",
    ]
    if overrides:
        rationale_parts.append("Deterministic Rule Overrides: " + " ".join(overrides))
    if conflict_reasons:
        rationale_parts.append("AI / Rule Divergence: " + " ".join(conflict_reasons))
    if extraction.clinical_rationale:
        rationale_parts.append(f"LLM Context: {extraction.clinical_rationale}")

    final_rationale = "\n".join(rationale_parts)

    return DeterministicTriageResult(
        final_severity=final_severity,
        final_ambulance=final_ambulance,
        ai_suggested_severity=ai_sev,
        ai_suggested_ambulance=ai_amb,
        deterministic_severity=rule_severity,
        deterministic_ambulance=rule_ambulance,
        has_conflict=has_conflict,
        conflict_reason="; ".join(conflict_reasons) if conflict_reasons else None,
        mandatory_human_review=mandatory_review,
        review_triggers=review_triggers,
        clinical_rationale=final_rationale,
        decision_type=DECISION_TYPE_HEURISTIC,
        disclaimer=PROTOTYPE_DISCLAIMER,
        is_multi_patient=is_multi_patient,
        patient_count=patient_count,
    )
