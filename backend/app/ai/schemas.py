"""Strict Pydantic schemas for the LLM intelligence layer."""
from typing import List, Optional
from pydantic import BaseModel, Field, ConfigDict, field_validator, model_validator

from app.models.case import SeverityLevel, AmbulanceType
from app.ai.normalization.schemas import EmergencyTypeStr


class EmergencyExtractionResult(BaseModel):
    """
    Strict clinical extraction result produced by the LLM Intelligence Layer.
    All LLM providers must output JSON strictly conforming to this schema.
    """
    emergency_type: str = Field(
        ...,
        description="Categorized emergency type, e.g. CARDIAC, Road Traffic Accident, Respiratory Distress, Burn Injury, Unclear/Pending",
    )
    symptoms: List[str] = Field(
        default_factory=list,
        description="List of clinical signs, symptoms, or reported conditions",
    )
    evidence: List[str] = Field(
        default_factory=list,
        description="Evidence statements grounding the clinical extraction in caller's narrative",
    )
    normalized_medical_text: Optional[str] = Field(
        default=None,
        description="Standardized English medical concepts for regional language expressions",
    )
    location: Optional[str] = Field(
        default=None,
        description="Mentioned landmark, street, intersection, station, or address. Null if not mentioned.",
    )
    severity: SeverityLevel = Field(
        default=SeverityLevel.MODERATE,
        description="Triage severity classification: CRITICAL, HIGH, MODERATE, or LOW",
    )
    patient_count: int = Field(
        default=1,
        ge=1,
        description="Estimated number of affected patients",
    )
    detected_language: str = Field(
        default="English",
        description="Detected language of caller: English, Hindi, Marathi, Code-Mixed, etc.",
    )
    ambulance_requirement: AmbulanceType = Field(
        default=AmbulanceType.BLS,
        description="Recommended ambulance type: ALS (Advanced Life Support) or BLS (Basic Life Support)",
    )
    missing_information: List[str] = Field(
        default_factory=list,
        description="List of critical emergency details missing from caller description (e.g. location, consciousness, caller number)",
    )
    conscious_status: Optional[str] = Field(
        default="unknown",
        description="Patient consciousness: conscious, unconscious, semi-conscious, or unknown",
    )
    breathing_status: Optional[str] = Field(
        default="unknown",
        description="Patient breathing: normal, difficulty, gasping, stopped, or unknown",
    )
    clinical_rationale: str = Field(
        default="Clinical triage assessment generated by AI intelligence layer.",
        description="Clinical rationale explaining the severity and ambulance assignment",
    )
    confidence_score: float = Field(
        default=0.8,
        ge=0.0,
        le=1.0,
        description="Confidence score for this extraction and classification between 0.0 and 1.0",
    )
    is_contradictory: bool = Field(
        default=False,
        description="Whether the caller description contains mutually contradictory statements",
    )
    contradiction_notes: Optional[str] = Field(
        default=None,
        description="Explanation of contradictions detected in the emergency description",
    )

    @model_validator(mode="before")
    @classmethod
    def normalize_keys(cls, data):
        if not isinstance(data, dict):
            return data
        d = dict(data)
        if "ambulance" in d and "ambulance_requirement" not in d:
            d["ambulance_requirement"] = d.pop("ambulance")
        if "missing_info" in d and "missing_information" not in d:
            d["missing_information"] = d.pop("missing_info")
        if "language" in d and "detected_language" not in d:
            d["detected_language"] = d.pop("language")
        if "rationale" in d and "clinical_rationale" not in d:
            d["clinical_rationale"] = d.pop("rationale")
        if "confidence" in d and "confidence_score" not in d:
            d["confidence_score"] = d.pop("confidence")
        if "type" in d and "emergency_type" not in d:
            d["emergency_type"] = d.pop("type")
        if "emergency_type" in d and d["emergency_type"]:
            d["emergency_type"] = EmergencyTypeStr(d["emergency_type"])
        if "consciousness" in d and "conscious_status" not in d:
            d["conscious_status"] = d.pop("consciousness")
        if "breathing" in d and "breathing_status" not in d:
            d["breathing_status"] = d.pop("breathing")
        if "evidence" in d and isinstance(d["evidence"], str):
            d["evidence"] = [d["evidence"]]
        return d

    @field_validator("patient_count", mode="before")
    @classmethod
    def normalize_patient_count(cls, v):
        if isinstance(v, str):
            import re
            digits = re.findall(r"\d+", v)
            if digits:
                return int(digits[0])
            return 1
        return v

    @field_validator("severity", mode="before")
    @classmethod
    def normalize_severity(cls, v):
        if isinstance(v, str):
            v_upper = v.strip().upper()
            if v_upper in SeverityLevel.__members__:
                return SeverityLevel[v_upper]
        return v

    @field_validator("ambulance_requirement", mode="before")
    @classmethod
    def normalize_ambulance(cls, v):
        if isinstance(v, str):
            v_upper = v.strip().upper()
            if v_upper in AmbulanceType.__members__:
                return AmbulanceType[v_upper]
        return v

    model_config = ConfigDict(extra="ignore")
