from typing import Optional, Dict, Any
from sqlalchemy import String, Integer, Float, Text, Enum, ForeignKey, Boolean, JSON
from sqlalchemy.orm import relationship, Mapped, mapped_column
from app.db.session import Base
from app.models.base import TimestampMixin
from app.models.case import SeverityLevel, AmbulanceType


class AIDecision(Base, TimestampMixin):
    """
    Explainable triage decision generated by the hybrid AI + rule decision engine.
    Clearly labeled as a PROTOTYPE DECISION-SUPPORT HEURISTIC (not clinically validated triage).
    Stores both AI suggestions and deterministic rule validation for full auditability.
    """
    __tablename__ = "ai_decisions"

    case_id: Mapped[str] = mapped_column(String(36), ForeignKey("cases.id", ondelete="CASCADE"), nullable=False, index=True)
    model_name: Mapped[str] = mapped_column(String(64), default="grok-beta-http", nullable=False)
    
    # Final consolidated decision from hybrid engine
    severity_assessment: Mapped[SeverityLevel] = mapped_column(Enum(SeverityLevel), nullable=False)
    recommended_ambulance_type: Mapped[AmbulanceType] = mapped_column(Enum(AmbulanceType), nullable=False)
    clinical_rationale: Mapped[str] = mapped_column(Text, nullable=False)
    confidence_score: Mapped[float] = mapped_column(Float, default=0.0)
    confidence_level: Mapped[str] = mapped_column(String(16), default="HIGH")  # HIGH (>=0.75), MEDIUM (0.50-0.74), LOW (<0.50)
    confidence_components: Mapped[dict] = mapped_column(JSON, default=dict)     # Breakdown of 6 weighted components
    latency_ms: Mapped[int] = mapped_column(Integer, default=0)
    tokens_used: Mapped[int] = mapped_column(Integer, default=0)

    # Auditing both AI suggestion and deterministic rule results
    ai_suggested_severity: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    ai_suggested_ambulance: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    deterministic_severity: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    deterministic_ambulance: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    has_conflict: Mapped[bool] = mapped_column(Boolean, default=False)
    conflict_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    decision_type: Mapped[str] = mapped_column(String(64), default="PROTOTYPE_DECISION_SUPPORT_HEURISTIC")
    disclaimer: Mapped[str] = mapped_column(Text, default="PROTOTYPE DECISION-SUPPORT HEURISTIC - NOT CLINICALLY VALIDATED TRIAGE")

    # Relationships
    case = relationship("Case", back_populates="ai_decisions")
